/**
 * Two accounts kept clear of the sample data, purely for walking someone
 * through the system. One starts from nothing; the other is one PDF away from
 * a ticket, so the moment it appears can be shown without any setup.
 */
function seed_demo_accounts(PDO $db, string $studentPassword, array &$log): void
{
    $hash = password_hash($studentPassword, PASSWORD_DEFAULT);

    $insert = $db->prepare(
        'INSERT INTO users (email, password_hash, role, name, initials, student_no, program, year_level, mobile, status, email_verified_at)
         VALUES (?, ?, "student", ?, ?, ?, ?, ?, ?, "active", NOW())'
    );

    /* 1 · A blank slate: upload three PDFs → ticket. */
    $insert->execute([
        'demo.student@g.batstate-u.edu.ph', $hash, 'Demo Student', 'DS',
        '00-00001', 'BS Information Technology', '3rd Year', '09170000001',
    ]);

    /* 2 · Waiver and COR already in; the school ID is the last thing missing. */
    $insert->execute([
        'demo.almost@g.batstate-u.edu.ph', $hash, 'Demo Almost', 'DA',
        '00-00002', 'BS Business Administration', '4th Year', '09170000002',
    ]);
    $userId = (int) $db->lastInsertId();

    $doc = $db->prepare(
        'INSERT INTO documents (user_id, doc_type, original_name, stored_name, size_bytes, status, uploaded_at)
         VALUES (?, ?, ?, ?, ?, "submitted", NOW())'
    );
    foreach (['waiver' => 'Waiver-00-00002.pdf', 'cor' => 'COR-00-00002.pdf'] as $type => $file) {
        [$stored, $bytes] = write_sample_document(DOCUMENT_TYPES[$type]['label'], 'Demo Almost - 00-00002');
        $doc->execute([$userId, $type, $file, $stored, $bytes]);
    }

    $log[] = 'Demo walkthrough accounts: demo.student (clean start) and demo.almost (2 of 3 uploaded).';
}

