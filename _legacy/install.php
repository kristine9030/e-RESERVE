/**
 * A tiny but valid one-page PDF, so the review screen has something real to open.
 * Text is limited to plain ASCII so the byte offsets in the xref stay correct.
 */
function sample_pdf(string $heading, string $line): string
{
    $clean = static fn(string $t): string => str_replace(['\\', '(', ')'], ['', '', ''], preg_replace('/[^\x20-\x7E]/', '', $t));
    $stream = "BT /F1 22 Tf 60 740 Td (" . $clean($heading) . ") Tj ET\n"
            . "BT /F1 13 Tf 60 705 Td (" . $clean($line) . ") Tj ET\n"
            . "BT /F1 10 Tf 60 670 Td (e-RESERVE demo record - generated by install.php) Tj ET\n";

    $objs   = [];
    $objs[] = "<< /Type /Catalog /Pages 2 0 R >>";
    $objs[] = "<< /Type /Pages /Kids [3 0 R] /Count 1 >>";
    $objs[] = "<< /Type /Page /Parent 2 0 R /MediaBox [0 0 612 792] /Contents 4 0 R /Resources << /Font << /F1 5 0 R >> >> >>";
    $objs[] = "<< /Length " . strlen($stream) . " >>\nstream\n" . $stream . "endstream";
    $objs[] = "<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>";

    $pdf     = "%PDF-1.4\n";
    $offsets = [];
    foreach ($objs as $i => $body) {
        $offsets[] = strlen($pdf);
        $pdf .= ($i + 1) . " 0 obj\n" . $body . "\nendobj\n";
    }
    $xref = strlen($pdf);
    $pdf .= "xref\n0 " . (count($objs) + 1) . "\n0000000000 65535 f \n";
    foreach ($offsets as $o) {
        $pdf .= sprintf("%010d 00000 n \n", $o);
    }
    $pdf .= "trailer\n<< /Size " . (count($objs) + 1) . " /Root 1 0 R >>\nstartxref\n" . $xref . "\n%%EOF\n";

    return $pdf;
}

/** Write a sample PDF into the protected upload folder and return its stored name. */
function write_sample_document(string $heading, string $line): array
{
    if (!is_dir(DOC_PATH)) {
        mkdir(DOC_PATH, 0755, true);
    }
    protect_upload_dir();

    $name = date('Ymd') . '-' . bin2hex(random_bytes(16)) . '.pdf';
    $body = sample_pdf($heading, $line);
    file_put_contents(DOC_PATH . '/' . $name, $body);

    return [$name, strlen($body)];
}

