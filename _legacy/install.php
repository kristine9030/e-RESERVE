if ($_SERVER['REQUEST_METHOD'] === 'POST' && !INSTALL_LOCKED) {
    try {
        /* ------------------------------------------------------------------
           1. Create the database, then connect to it
        ------------------------------------------------------------------ */
        $root = new PDO(
            sprintf('mysql:host=%s;port=%d;charset=%s', DB_HOST, DB_PORT, DB_CHARSET),
            DB_USER,
            DB_PASS,
            [PDO::ATTR_ERRMODE => PDO::ERRMODE_EXCEPTION]
        );
        $root->exec('CREATE DATABASE IF NOT EXISTS `' . DB_NAME . '` CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci');
        $log[] = 'Database `' . DB_NAME . '` is ready.';

        $root->exec('USE `' . DB_NAME . '`');

        /* ------------------------------------------------------------------
           2. Schema
        ------------------------------------------------------------------ */
        $sql = file_get_contents(__DIR__ . '/database/schema.sql');
        if ($sql === false) {
            throw new RuntimeException('database/schema.sql is missing.');
        }
        $root->exec($sql);
        $log[] = 'Tables created (users, enrolled_students, documents, tickets, checkins, audit, sequences).';

        /* The registrar masterlist survives re-installs; load it once. */
        if ((int) $root->query('SELECT COUNT(*) FROM enrolled_students')->fetchColumn() === 0) {
            $list = __DIR__ . '/database/enrolled_students.sql';
            if (is_file($list)) {
                $root->exec((string) file_get_contents($list));
                $n = (int) $root->query('SELECT COUNT(*) FROM enrolled_students')->fetchColumn();
                $log[] = 'Masterlist loaded: ' . number_format($n) . ' enrolled students.';
            } else {
                $log[] = 'database/enrolled_students.sql not found — masterlist NOT loaded.';
            }
        }

        /* ------------------------------------------------------------------
           3. Seed
        ------------------------------------------------------------------ */
        seed_everything($root, $staffPassword, $studentPassword, $log);

        $done = true;
    } catch (Throwable $ex) {
        $errors[] = $ex->getMessage();
    }
}

